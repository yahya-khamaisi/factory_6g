"""Export the four-channel characterisation table for Chapter 3.

Draws channel responses exactly as the Monte Carlo pipeline does (the
ray-traced model from the evaluation split) and writes
``thesis/generated/tab_channel_characterisation.tex``.

Usage (inside Docker):
    python scripts/tools/export_channel_characterisation.py --slots 2048
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from factory6g.sim.rng import seed_all

from factory6g.models.model import Model
from factory6g.sim.config import load_config

CHANNELS = (
    ("rayleigh", "Rayleigh"),
    ("rician", r"Rician"),
    ("tr38901", "TR~38.901 UMi"),
    ("raytraced", "Ray-traced"),
)


def characterise(h: np.ndarray) -> dict[str, float]:
    """``h``: [B, 1, M, U, 1, S, F] frequency response."""
    h = h[:, 0, :, :, 0, 0, :]                                   # [B, M, U, F]
    num_bs_ant, num_ut = h.shape[1], h.shape[2]
    H = np.transpose(h, (0, 3, 1, 2)).reshape(-1, num_bs_ant, num_ut)
    # Unit-norm columns: correlation and conditioning describe spatial structure
    # only, independent of each terminal's large-scale gain.
    Hn = H / np.linalg.norm(H, axis=1, keepdims=True)
    gram = np.abs(np.einsum("nmi,nmj->nij", Hn.conj(), Hn))
    corr = gram[:, ~np.eye(num_ut, dtype=bool)]
    sv = np.linalg.svd(Hn, compute_uv=False)
    cond_db = 20 * np.log10(sv[:, 0] / sv[:, -1])
    hn = h / np.sqrt(np.mean(np.abs(h) ** 2, axis=(1, 3), keepdims=True))
    fsel = np.mean(np.var(np.abs(hn), axis=-1)) / np.mean(np.abs(hn) ** 2)
    return {
        "corr_mean": float(corr.mean()),
        "corr_p90": float(np.percentile(corr, 90)),
        "cond_median": float(np.median(cond_db)),
        "cond_p90": float(np.percentile(cond_db, 90)),
        "fsel": float(fsel),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="config/config.json")
    parser.add_argument("--slots", type=int, default=2048)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--output", default="thesis/generated/tab_channel_characterisation.tex")
    args = parser.parse_args()

    base = load_config(args.config).system_runtime_config
    rows = []
    for key, label in CHANNELS:
        seed_all(args.seed)
        cfg = dict(base, channel_model_type=key, rt_bank_split="eval", large_scale_model="hall")
        channel = Model(cfg, estimator_type="ls").get_channel()
        # Many short batches, so the statistics cover many terminal positions.
        chunks, gains = [], []
        for _ in range(max(1, args.slots // 8)):
            chunks.append(channel.sample_frequency_response(8).numpy())
            if channel.last_large_scale is not None:
                gains.append(channel.last_large_scale["gain_db"])
        stats = characterise(np.concatenate(chunks, axis=0))
        g = np.concatenate(gains) if gains else np.zeros(1)
        stats["gain_spread_db"] = float(np.percentile(g, 90) - np.percentile(g, 10))
        print(key, stats, flush=True)
        rows.append(
            f"    {label} & {stats['corr_mean']:.2f} & {stats['corr_p90']:.2f} & "
            f"{stats['cond_median']:.1f} & {stats['cond_p90']:.1f} & {stats['fsel']:.3f} & "
            f"{stats['gain_spread_db']:.1f} \\\\"
        )

    lines = [
        "% Auto-generated by scripts/tools/export_channel_characterisation.py — do not edit by hand.",
        r"\begin{tabular}{lcccccc}",
        r"  \toprule",
        r"  \tablehead \textbf{Channel} & \multicolumn{2}{c}{\textbf{Correlation}}"
        r" & \multicolumn{2}{c}{\textbf{Cond.\ no.\ (dB)}} & \textbf{Freq.} & \textbf{Gain} \\",
        r"  \tablehead & \textbf{mean} & \textbf{p90} & \textbf{med.} & \textbf{p90} & \textbf{sel.} & \textbf{spread (dB)} \\",
        r"  \midrule",
        *rows,
        r"  \bottomrule",
        r"\end{tabular}",
    ]
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
