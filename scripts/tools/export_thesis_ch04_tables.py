#!/usr/bin/env python3
"""Export the Chapter 4 synthesis tables that are derived from the locked runs.

Reads ``thesis/notes/planning/canonical_runs.json`` for the run directories of
Run B, Run C and Run D, and writes three LaTeX fragments to ``thesis/generated/``:

* ``ch04_ce_gain.tex``      -- Run C: BER ratio of each estimator to LS at anchor points.
* ``ch04_rm_service.tex``   -- Run B: throughput, allocated power and Jain's index at 0 and 30 dB.
* ``ch04_coupled_gain.tex`` -- Run D: estimator gain under each scheduler and the genie gap.

Every number is read from ``stage_results_v2.json``; a ratio that involves an
upper-bound-only point (Algorithm 3.2 in the thesis: fewer than 30 bit errors
or errors in fewer than 10 batches) is marked with a dagger. Run inside the
Docker image::

    docker compose run --rm -v "$PWD/scripts:/app/scripts:ro" \
        -v "$PWD/thesis:/app/thesis" --entrypoint python simulation \
        scripts/tools/export_thesis_ch04_tables.py
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

CHANNEL_LABELS = {
    "rayleigh": "Rayleigh",
    "rician": "Rician",
    "tr38901": "TR 38.901 UMi",
    "raytraced": "Ray-traced hall",
}
ESTIMATOR_LABELS = {
    "ls": "LS",
    "dft": "DFT",
    "lmmse": "LMMSE",
    "adaptive": "Adaptive",
    "neural": "Neural",
    "perfect": "Genie",
}
SCHEDULER_LABELS = {
    "static": "Static",
    "round_robin": "Round-robin",
    "max_throughput": "Max-throughput",
    "pf": "PF",
    "wmmse": "WMMSE",
    "queue_aware": "Queue-aware",
    "drl": "DRL",
    "reliability_drl": "Reliability-aware DRL",
}
RUN_B_ORDER = ["static", "round_robin", "max_throughput", "pf", "wmmse", "queue_aware", "drl", "reliability_drl"]
RUN_D_SCHEDULERS = ["static", "max_throughput", "pf", "wmmse", "drl", "reliability_drl"]


def load(path: Path) -> dict:
    with path.open() as fh:
        return json.load(fh)


def point_index(stage: dict, ebno_db: float) -> int:
    grid = [float(x) for x in stage["ebno_db_range"]]
    for i, value in enumerate(grid):
        if abs(value - ebno_db) < 1e-9:
            return i
    raise KeyError(f"{ebno_db} dB not in sweep {grid}")


def resolved(method: dict, i: int) -> bool:
    status = method.get("point_status")
    if status is not None:
        return str(status[i]) == "resolved"
    # Estimator stage files of Run A predate the status field: apply the rule.
    bit_errors = float(method["bit_errors"][i])
    error_batches = method.get("error_batches")
    enough_batches = True if error_batches is None else float(error_batches[i]) >= 10
    return bit_errors >= 30 and enough_batches


def ratio_cell(num: dict, den: dict, i: int) -> str:
    """BER(num)/BER(den) with a dagger when either point is a bound."""
    b_num = float(num["ber"][i])
    b_den = float(den["ber"][i])
    flag = "" if resolved(num, i) and resolved(den, i) else "$^{\\dagger}$"
    if b_den <= 0.0:
        return "---" + flag
    value = b_num / b_den
    if value >= 100:
        text = f"{value:.0f}"
    elif value >= 10:
        text = f"{value:.1f}"
    else:
        text = f"{value:.2f}"
    return text + flag


def sci(value: float) -> str:
    if value <= 0:
        return "0"
    exp = int(math.floor(math.log10(value)))
    mant = value / 10**exp
    return f"${mant:.2f}\\times10^{{{exp}}}$"


HEADER = "% Auto-generated by scripts/tools/export_thesis_ch04_tables.py from the locked\n% stage_results_v2.json files -- do not edit by hand.\n"


def table_ce_gain(canon: dict, out_dir: Path) -> None:
    run = canon["estimator_matrix_run"]
    anchors = [0.0, 6.0, 9.0, 15.0]
    lines = [HEADER]
    lines.append("\\begin{table}[htbp]")
    lines.append("  \\centering")
    lines.append(
        "  \\caption{BER of LS divided by the BER of each refinement on shared inputs "
        "(Run~C), by channel model and operating point: a value of 2 means the "
        "refinement halves the decoded BER of LS on the same channel and noise draws.}"
    )
    lines.append("  \\label{tab:ch04-ce-gain}")
    lines.append("  \\small")
    lines.append("  \\setlength{\\tabcolsep}{5pt}")
    lines.append("  \\begin{tabular}{l" + "r" * len(anchors) + "}")
    lines.append("    \\toprule")
    head = " & ".join(f"\\textbf{{{int(a)}\\,dB}}" for a in anchors)
    lines.append(f"    \\tablehead \\textbf{{Estimator}} & {head} \\\\")
    lines.append("    \\midrule")
    first = True
    for channel, rel in run["channels"].items():
        stage = load(Path(run["dir"]) / rel)
        methods = stage["methods"]
        if not first:
            lines.append("    \\midrule")
        first = False
        lines.append(f"    \\tablegroup{{{len(anchors) + 1}}}{{{CHANNEL_LABELS[channel]}}} \\\\")
        for est in ["dft", "lmmse", "adaptive", "neural"]:
            cells = [ratio_cell(methods["ls"], methods[est], point_index(stage, a)) for a in anchors]
            lines.append(f"    {ESTIMATOR_LABELS[est]} & " + " & ".join(cells) + " \\\\")
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append(
        "  \\tablenote{$\\dagger$: at least one of the two BER values is an "
        "upper-bound-only point, so the ratio is indicative rather than resolved.}"
    )
    lines.append("\\end{table}")
    (out_dir / "ch04_ce_gain.tex").write_text("\n".join(lines) + "\n")


def table_rm_service(canon: dict, out_dir: Path) -> None:
    run = canon["resource_managers_run"]
    lines = [HEADER]
    lines.append("\\begin{table}[htbp]")
    lines.append("  \\centering")
    lines.append(
        "  \\caption{Service metrics of the eight schedulers at $E_b/N_0 = 0$ and 30\\,dB "
        "(Run~B): correctly delivered information bits per batch $T$, "
        "Eq.~\\eqref{eq:throughput}; allocated uplink transmit power $P_{\\mathrm{tx}}$, "
        "Eq.~\\eqref{eq:tx-power}; and Jain's index $\\mathcal{J}$ over per-terminal "
        "delivered bits, Eq.~\\eqref{eq:jain}. The throughput ceiling is 122{,}880 "
        "bits per batch for static activation and 61{,}440 for the two-terminal "
        "schedulers.}"
    )
    lines.append("  \\label{tab:ch04-rm-service}")
    # 32 body rows plus group and header rows: footnotesize and a tighter
    # stretch keep the table on one page inside the guideline margins.
    lines.append("  \\footnotesize")
    lines.append("  \\renewcommand{\\arraystretch}{1.12}")
    lines.append("  \\setlength{\\tabcolsep}{4pt}")
    lines.append("  \\begin{tabular}{lrrrrrr}")
    lines.append("    \\toprule")
    lines.append(
        "    \\tablehead \\textbf{Scheduler} & \\multicolumn{2}{c}{\\textbf{$T$ (bits/batch)}} "
        "& \\multicolumn{2}{c}{\\textbf{$P_{\\mathrm{tx}}$ (W)}} "
        "& \\multicolumn{2}{c}{\\textbf{$\\mathcal{J}$}} \\\\"
    )
    lines.append("    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}")
    lines.append("    \\tablehead & 0\\,dB & 30\\,dB & 0\\,dB & 30\\,dB & 0\\,dB & 30\\,dB \\\\")
    lines.append("    \\midrule")
    first = True
    for channel, rel in run["channels"].items():
        stage = load(Path(run["dir"]) / rel)
        methods = stage["methods"]
        i0, i30 = point_index(stage, 0.0), point_index(stage, 30.0)
        if not first:
            lines.append("    \\midrule")
        first = False
        lines.append(f"    \\tablegroup{{7}}{{{CHANNEL_LABELS[channel]}}} \\\\")
        for sched in RUN_B_ORDER:
            m = methods[sched]
            cells = [
                f"{float(m['throughput_bits_per_batch'][i0]):,.0f}".replace(",", "{,}"),
                f"{float(m['throughput_bits_per_batch'][i30]):,.0f}".replace(",", "{,}"),
                f"{float(m['tx_power_w'][i0]):.2f}",
                f"{float(m['tx_power_w'][i30]):.2f}",
                f"{float(m['jain_fairness'][i0]):.2f}",
                f"{float(m['jain_fairness'][i30]):.2f}",
            ]
            lines.append(f"    {SCHEDULER_LABELS[sched]} & " + " & ".join(cells) + " \\\\")
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append(
        "  \\tablenote{Round-robin's index below 1 at 30\\,dB on Rayleigh and Rician "
        "fading is the shared-pointer artefact of Section~\\ref{sec:results-rm-fairness}, "
        "not a property of the rule.}"
    )
    lines.append("\\end{table}")
    (out_dir / "ch04_rm_service.tex").write_text("\n".join(lines) + "\n")


def table_coupled_gain(canon: dict, out_dir: Path) -> None:
    run = canon["coupled_run"]
    lines = [HEADER]
    lines.append("\\begin{table}[htbp]")
    lines.append("  \\centering")
    lines.append(
        "  \\caption{Estimation gain and genie gap under each scheduler (Run~D). "
        "``Neural gain'' is the BER with LS CSI divided by the BER with neural CSI "
        "under the same scheduler on the same draws; ``genie gap'' is the BER with "
        "neural CSI divided by the BER with perfect CSI, so a value near 1 means "
        "little estimation gain remains to be had.}"
    )
    lines.append("  \\label{tab:ch04-coupled-gain}")
    lines.append("  \\small")
    lines.append("  \\setlength{\\tabcolsep}{4pt}")
    lines.append("  \\begin{tabular}{lrrrrr}")
    lines.append("    \\toprule")
    lines.append(
        "    \\tablehead \\textbf{Scheduler} & \\multicolumn{2}{c}{\\textbf{Neural gain}} "
        "& \\multicolumn{2}{c}{\\textbf{Genie gap}} & \\textbf{LS to genie} \\\\"
    )
    lines.append("    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-6}")
    lines.append("    \\tablehead & 0\\,dB & 6\\,dB & 0\\,dB & 6\\,dB & 0\\,dB \\\\")
    lines.append("    \\midrule")
    first = True
    for channel, rel in run["channels"].items():
        stage = load(Path(run["dir"]) / rel)
        methods = stage["methods"]
        i0, i6 = point_index(stage, 0.0), point_index(stage, 6.0)
        if not first:
            lines.append("    \\midrule")
        first = False
        lines.append(f"    \\tablegroup{{6}}{{{CHANNEL_LABELS[channel]}}} \\\\")
        for sched in RUN_D_SCHEDULERS:
            ls, nn, genie = (methods[f"{e}+{sched}"] for e in ("ls", "neural", "perfect"))
            cells = [
                ratio_cell(ls, nn, i0),
                ratio_cell(ls, nn, i6),
                ratio_cell(nn, genie, i0),
                ratio_cell(nn, genie, i6),
                ratio_cell(ls, genie, i0),
            ]
            lines.append(f"    {SCHEDULER_LABELS[sched]} & " + " & ".join(cells) + " \\\\")
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append(
        "  \\tablenote{$\\dagger$: at least one BER in the ratio is an upper-bound-only "
        "point. A genie gap below 1 means the scheduler did \\emph{worse} with perfect "
        "CSI than with the neural estimate.}"
    )
    lines.append("\\end{table}")
    (out_dir / "ch04_coupled_gain.tex").write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--canonical", default="thesis/notes/planning/canonical_runs.json")
    parser.add_argument("--out-dir", default="thesis/generated")
    args = parser.parse_args()
    canon = load(Path(args.canonical))
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    table_ce_gain(canon, out_dir)
    table_rm_service(canon, out_dir)
    table_coupled_gain(canon, out_dir)
    for name in ("ch04_ce_gain.tex", "ch04_rm_service.tex", "ch04_coupled_gain.tex"):
        print(f"wrote {out_dir / name}")


if __name__ == "__main__":
    main()
